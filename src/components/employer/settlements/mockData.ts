export function getLifecycleStats(batches: SettlementBatch[]) {
  const ready = batches.filter(b => b.status === 'ready');
  const exported = batches.filter(b => b.status === 'exported');
  const paid = batches.filter(b => b.status === 'paid');
  
  return {
    ready: {
      count: ready.length,
      totalAED: ready.reduce((sum, b) => sum + b.totalAED, 0),
      claims: ready.reduce((sum, b) => sum + b.claimsCount, 0),
    },
    exported: {
      count: exported.length,
      totalAED: exported.reduce((sum, b) => sum + b.totalAED, 0),
      claims: exported.reduce((sum, b) => sum + b.claimsCount, 0),
    },
    paid: {
      count: paid.length,
      totalAED: paid.reduce((sum, b) => sum + b.totalAED, 0),
      claims: paid.reduce((sum, b) => sum + b.claimsCount, 0),
    },
    exceptions: {
      critical: mockExceptions.filter(e => e.severity === 'critical').length,
      warning: mockExceptions.filter(e => e.severity === 'warning').length,
      totalAED: mockExceptions.reduce((sum, e) => sum + e.expectedAmount, 0),
    },
  };
}
